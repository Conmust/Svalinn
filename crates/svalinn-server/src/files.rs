//! Uploaded files (attachments, emojis, server icons), served only to people
//! allowed to see them.
//!
//! Files live in `uploads/` and are stored in the database as `/uploads/<name>`.
//! They are not served from that path. Instead, every API response that
//! contains a file path gets a signed link instead:
//!
//!   /api/v1/files/<name>?u=<user>&s=<session>&e=<expiry>&sig=<hmac>
//!
//! The link is tied to the viewer's login session. Each time it's fetched the
//! server checks the signature and expiry, that the account isn't banned and
//! the session is still active, and that the viewer is a member of the server
//! the file belongs to (channel attachments, emojis, server icons) or a
//! participant of the DM conversation it belongs to (DM attachments). A ban,
//! logout, leaving a server, or no longer being a DM participant therefore
//! stops access to saved links immediately.

use axum::{
    body::Body,
    extract::{Path, Query, Request, State},
    http::{header, HeaderValue, StatusCode},
    response::{IntoResponse, Response},
};
use hmac::{Hmac, Mac};
use serde::Deserialize;
use sha2::Sha256;
use tower::ServiceExt;
use tower_http::services::ServeFile;
use uuid::Uuid;

use crate::db::Database;

/// How long a signed link works. Access is re-checked on every request, so
/// this mainly limits how long a link copied to someone else keeps working.
pub const SIGNED_LINK_TTL_SECONDS: i64 = 6 * 60 * 60;

const STORED_PREFIX: &str = "/uploads/";
const ROUTE_PREFIX: &str = "/api/v1/files/";
const UPLOAD_DIR: &str = "uploads";

/// JSON keys whose values may hold file paths (see `sign_json`).
const FILE_KEYS: [&str; 4] = ["attachment_url", "url", "icon_url", "avatar_url"];

type HmacSha256 = Hmac<Sha256>;

/// Upload file names are generated by the server: letters, digits, `_`, `-`
/// and one extension. Anything else (like `..` or `/`) is rejected.
fn valid_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 200
        && !name.starts_with('.')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.'))
        && !name.contains("..")
}

fn mac(name: &str, user_id: Uuid, session_id: Uuid, expires: i64) -> HmacSha256 {
    // Keyed with the server secret; the "file" prefix keeps these signatures
    // distinct from anything else signed with the same secret.
    let mut mac = HmacSha256::new_from_slice(crate::extractors::auth::jwt_secret())
        .expect("HMAC accepts any key length");
    mac.update(format!("file\0{name}\0{user_id}\0{session_id}\0{expires}").as_bytes());
    mac
}

fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn from_hex(s: &str) -> Option<Vec<u8>> {
    if s.len() % 2 != 0 {
        return None;
    }
    (0..s.len()).step_by(2).map(|i| u8::from_str_radix(s.get(i..i + 2)?, 16).ok()).collect()
}

/// Turns a stored `/uploads/<name>` path into a signed link for this viewer.
/// Anything else (an external URL, say) is returned unchanged.
pub fn sign_path(path: &str, user_id: Uuid, session_id: Uuid) -> String {
    let Some(name) = path.strip_prefix(STORED_PREFIX).filter(|n| valid_name(n)) else {
        return path.to_string();
    };
    let expires = chrono::Utc::now().timestamp() + SIGNED_LINK_TTL_SECONDS;
    let sig = to_hex(&mac(name, user_id, session_id, expires).finalize().into_bytes());
    format!("{ROUTE_PREFIX}{name}?u={user_id}&s={session_id}&e={expires}&sig={sig}")
}

pub fn sign_opt(path: &mut Option<String>, user_id: Uuid, session_id: Uuid) {
    if let Some(p) = path {
        *p = sign_path(p, user_id, session_id);
    }
}

/// Signs file paths anywhere in a JSON value (used for WebSocket events,
/// which are signed separately for each recipient).
pub fn sign_json(value: &mut serde_json::Value, user_id: Uuid, session_id: Uuid) {
    match value {
        serde_json::Value::Object(map) => {
            for (key, v) in map.iter_mut() {
                match v {
                    serde_json::Value::String(s) if FILE_KEYS.contains(&key.as_str()) => {
                        *s = sign_path(s, user_id, session_id);
                    }
                    _ => sign_json(v, user_id, session_id),
                }
            }
        }
        serde_json::Value::Array(items) => {
            for v in items {
                sign_json(v, user_id, session_id);
            }
        }
        _ => {}
    }
}

/// The form to store in the database. Accepts a signed link (with or without
/// the server's address in front), a `/uploads/...` path, or any other URL,
/// which is kept as it is. Used when clients send a file link back to us.
pub fn stored_path(url: &str) -> String {
    let path = match url.find(ROUTE_PREFIX) {
        Some(i) => &url[i + ROUTE_PREFIX.len()..],
        None => match url.find(STORED_PREFIX) {
            Some(i) => &url[i + STORED_PREFIX.len()..],
            None => return url.to_string(),
        },
    };
    let name = path.split(['?', '#']).next().unwrap_or("");
    if valid_name(name) {
        format!("{STORED_PREFIX}{name}")
    } else {
        url.to_string()
    }
}

/// Whether `url` (as normalized by `stored_path`) is one of our own
/// `/uploads/...` paths, as opposed to an external URL kept as-is.
pub fn is_stored_path(url: &str) -> bool {
    url.starts_with(STORED_PREFIX) && valid_name(&url[STORED_PREFIX.len()..])
}

/// Whether `stored` (a `/uploads/...` path, as normalized by `stored_path`)
/// is already in use as a channel/DM attachment, a custom emoji, or a
/// server icon. Used to stop `routes::users::update_avatar` from pointing a
/// user's (globally-visible) avatar at a file they only know the name of
/// because they're a legitimate recipient of it elsewhere (e.g. a private
/// DM attachment) -- without this check, setting it as an avatar would make
/// `serve_file`'s avatar-visibility branch expose it to every user, not just
/// the people it was originally shared with.
pub async fn is_file_used_elsewhere(db: &Database, stored: &str) -> Result<bool, sqlx::Error> {
    sqlx::query_scalar(
        r#"
        SELECT EXISTS(
            SELECT 1 FROM messages WHERE attachment_url = $1
            UNION
            SELECT 1 FROM custom_emojis WHERE url = $1
            UNION
            SELECT 1 FROM servers WHERE icon_url = $1
        )
        "#,
    )
    .bind(stored)
    .fetch_one(&db.pool)
    .await
}

/// Deletes uploaded files given their stored `/uploads/...` paths. Missing
/// files and anything that isn't an upload path are skipped.
pub async fn remove_stored_files(paths: &[String]) {
    for path in paths {
        if let Some(name) = path.strip_prefix(STORED_PREFIX).filter(|n| valid_name(n)) {
            let _ = tokio::fs::remove_file(std::path::Path::new(UPLOAD_DIR).join(name)).await;
        }
    }
}

#[derive(Deserialize)]
pub struct FileQuery {
    u: Uuid,
    s: Uuid,
    e: i64,
    sig: String,
}

/// GET /api/v1/files/:name?u=&s=&e=&sig=
pub async fn serve_file(
    State(db): State<Database>,
    Path(name): Path<String>,
    Query(q): Query<FileQuery>,
    request: Request,
) -> Response {
    let denied = |status: StatusCode| status.into_response();

    if !valid_name(&name) {
        return denied(StatusCode::NOT_FOUND);
    }

    // 1. Signature (constant-time comparison) and expiry
    let Some(sig) = from_hex(&q.sig) else {
        return denied(StatusCode::FORBIDDEN);
    };
    if mac(&name, q.u, q.s, q.e).verify_slice(&sig).is_err() {
        return denied(StatusCode::FORBIDDEN);
    }
    let remaining = q.e - chrono::Utc::now().timestamp();
    if remaining <= 0 {
        return denied(StatusCode::FORBIDDEN);
    }

    // 2. Account not banned, session still active
    if crate::sessions::check_access(&db, q.u, q.s).await.is_err() {
        return denied(StatusCode::FORBIDDEN);
    }

    // 3. Viewer is a member of the server the file belongs to (channel
    // attachments, custom emojis, server icons) OR a participant of the DM
    // conversation it belongs to (DM attachments -- added alongside
    // encrypted DM attachments; applies to legacy plaintext DM attachments
    // too, which had no access check covering them at all before this) OR
    // the file is someone's profile picture, which (like a username) is
    // visible to any logged-in user regardless of shared servers/DMs --
    // the "+ New Message" picker already lists every user site-wide by
    // username, so gating avatars the way attachments are gated would just
    // mean some of those listed people show a broken image instead of
    // actually hiding anything.
    let allowed: bool = sqlx::query_scalar(
        r#"
        SELECT EXISTS(
            SELECT 1 FROM server_members sm
            WHERE sm.user_id = $2 AND sm.server_id IN (
                SELECT c.server_id FROM messages m JOIN channels c ON c.id = m.channel_id
                WHERE m.attachment_url = $1
                UNION
                SELECT server_id FROM custom_emojis WHERE url = $1
                UNION
                SELECT id FROM servers WHERE icon_url = $1
            )
        ) OR EXISTS(
            SELECT 1 FROM conversation_participants cp
            JOIN messages m ON m.conversation_id = cp.conversation_id
            WHERE cp.user_id = $2 AND m.attachment_url = $1
        ) OR EXISTS(
            SELECT 1 FROM users WHERE avatar_url = $1
        )
        "#,
    )
    .bind(format!("{STORED_PREFIX}{name}"))
    .bind(q.u)
    .fetch_one(&db.pool)
    .await
    .unwrap_or(false);
    if !allowed {
        return denied(StatusCode::NOT_FOUND);
    }

    // 4. Serve it (ServeFile handles content types and range requests, so
    //    video seeking works).
    let path = std::path::Path::new(UPLOAD_DIR).join(&name);
    let mut response = match ServeFile::new(path).oneshot(request).await {
        Ok(response) => response.map(Body::new),
        Err(_) => return denied(StatusCode::INTERNAL_SERVER_ERROR),
    };
    if response.status() == StatusCode::NOT_FOUND {
        return response;
    }

    let headers = response.headers_mut();
    if let Ok(v) = HeaderValue::from_str(&format!("private, max-age={remaining}")) {
        headers.insert(header::CACHE_CONTROL, v);
    }
    // Uploaded files are untrusted: never run them as a page or script.
    headers.insert(header::X_CONTENT_TYPE_OPTIONS, HeaderValue::from_static("nosniff"));
    headers.insert(header::CONTENT_SECURITY_POLICY, HeaderValue::from_static("sandbox"));
    let inline = headers
        .get(header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .is_some_and(|t| t.starts_with("image/") || t.starts_with("video/") || t.starts_with("audio/"));
    if !inline {
        headers.insert(header::CONTENT_DISPOSITION, HeaderValue::from_static("attachment"));
    }
    response
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::body::Body;
    use axum::extract::{Path as AxumPath, Query as AxumQuery, State as AxumState};

    async fn test_db() -> Database {
        dotenvy::dotenv().ok();
        let database_url = std::env::var("DATABASE_URL").expect("DATABASE_URL is required for tests");
        Database::new(&database_url).await.expect("failed to connect to test database")
    }

    async fn create_test_user(db: &Database) -> Uuid {
        let unique = Uuid::new_v4();
        sqlx::query_scalar(
            "INSERT INTO users (username, email, password_hash, display_name) VALUES ($1, $2, $3, $4) RETURNING id",
        )
        .bind(format!("user_{unique}"))
        .bind(format!("{unique}@example.com"))
        .bind("hash")
        .bind("Test User")
        .fetch_one(&db.pool)
        .await
        .expect("failed to create test user")
    }

    async fn cleanup_test_user(db: &Database, user_id: Uuid) {
        let _ = sqlx::query("DELETE FROM users WHERE id = $1").bind(user_id).execute(&db.pool).await;
    }

    /// `check_access` (called by `serve_file` before its own membership
    /// check even runs) requires a real, unexpired, unrevoked
    /// `refresh_tokens` row for (user_id, session_id) -- a session id that
    /// isn't backed by one is indistinguishable from a logged-out session
    /// and gets denied before the access check this test exists to cover.
    async fn create_test_session(db: &Database, user_id: Uuid) -> Uuid {
        let session_id = Uuid::new_v4();
        sqlx::query(
            "INSERT INTO refresh_tokens (user_id, family_id, token_hash, expires_at) VALUES ($1, $2, $3, NOW() + INTERVAL '1 hour')",
        )
        .bind(user_id)
        .bind(session_id)
        .bind(format!("test-hash-{}", Uuid::new_v4()))
        .execute(&db.pool)
        .await
        .expect("failed to create test session");
        session_id
    }

    fn query_for(name: &str, user_id: Uuid, session_id: Uuid) -> AxumQuery<FileQuery> {
        let signed = sign_path(&format!("{STORED_PREFIX}{name}"), user_id, session_id);
        let (path, qs) = signed.split_once('?').expect("sign_path must produce a query string");
        assert_eq!(path, format!("{ROUTE_PREFIX}{name}"));
        let uri: axum::http::Uri = format!("http://x/{path}?{qs}").parse().expect("valid uri");
        AxumQuery::<FileQuery>::try_from_uri(&uri).expect("signed query string must parse")
    }

    /// A DM participant can fetch a DM attachment's signed link; a
    /// non-participant with an otherwise validly-signed link (correct
    /// secret, correct expiry -- just not a participant of the
    /// conversation the file belongs to) cannot. Exercises the
    /// `conversation_participants` branch added to `serve_file`'s access
    /// check -- before it existed, EVERY DM attachment 404'd for everyone,
    /// participant included, since the old check only recognized
    /// server-channel attachments.
    #[tokio::test]
    async fn dm_participant_can_fetch_dm_attachment_but_outsider_cannot() {
        init_secret();
        let db = test_db().await;
        let participant = create_test_user(&db).await;
        let other_participant = create_test_user(&db).await;
        let outsider = create_test_user(&db).await;

        let conversation_id: Uuid = sqlx::query_scalar("INSERT INTO conversations DEFAULT VALUES RETURNING id")
            .fetch_one(&db.pool)
            .await
            .expect("failed to create test conversation");
        sqlx::query("INSERT INTO conversation_participants (conversation_id, user_id) VALUES ($1, $2), ($1, $3)")
            .bind(conversation_id)
            .bind(participant)
            .bind(other_participant)
            .execute(&db.pool)
            .await
            .expect("failed to add test participants");

        let stored_name = format!("test_{}.txt", Uuid::new_v4());
        sqlx::query(
            "INSERT INTO messages (conversation_id, channel_id, user_id, content, attachment_url, is_encrypted) VALUES ($1, NULL, $2, 'hi', $3, false)",
        )
        .bind(conversation_id)
        .bind(participant)
        .bind(format!("{STORED_PREFIX}{stored_name}"))
        .execute(&db.pool)
        .await
        .expect("failed to insert test message");

        tokio::fs::create_dir_all(UPLOAD_DIR).await.expect("failed to create uploads dir");
        let file_path = std::path::Path::new(UPLOAD_DIR).join(&stored_name);
        tokio::fs::write(&file_path, b"test attachment bytes").await.expect("failed to write test file");

        let participant_session = create_test_session(&db, participant).await;
        let outsider_session = create_test_session(&db, outsider).await;
        let dummy_request = || Request::builder().body(Body::empty()).expect("valid request");

        let participant_response = serve_file(
            AxumState(db.clone()),
            AxumPath(stored_name.clone()),
            query_for(&stored_name, participant, participant_session),
            dummy_request(),
        )
        .await;
        assert_eq!(participant_response.status(), StatusCode::OK, "a participant must be able to fetch a DM attachment");

        let outsider_response = serve_file(
            AxumState(db.clone()),
            AxumPath(stored_name.clone()),
            query_for(&stored_name, outsider, outsider_session),
            dummy_request(),
        )
        .await;
        assert_eq!(
            outsider_response.status(),
            StatusCode::NOT_FOUND,
            "a non-participant must not be able to fetch a DM attachment, even with an otherwise validly-signed link"
        );

        let _ = tokio::fs::remove_file(&file_path).await;
        let _ = sqlx::query("DELETE FROM conversations WHERE id = $1").bind(conversation_id).execute(&db.pool).await;
        cleanup_test_user(&db, participant).await;
        cleanup_test_user(&db, other_participant).await;
        cleanup_test_user(&db, outsider).await;
    }

    fn init_secret() {
        std::env::set_var("JWT_SECRET", "x".repeat(40));
        let _ = crate::extractors::auth::init_jwt_secret();
    }

    #[test]
    fn rejects_unsafe_names() {
        assert!(valid_name("msg_1f0e_ab.png"));
        assert!(!valid_name("../.env"));
        assert!(!valid_name("a/b.png"));
        assert!(!valid_name(".env"));
        assert!(!valid_name("a..b"));
        assert!(!valid_name(""));
    }

    #[test]
    fn signs_only_upload_paths_and_round_trips() {
        init_secret();
        let (u, s) = (Uuid::new_v4(), Uuid::new_v4());
        let signed = sign_path("/uploads/emoji_1.png", u, s);
        assert!(signed.starts_with("/api/v1/files/emoji_1.png?u="));
        assert_eq!(stored_path(&signed), "/uploads/emoji_1.png");
        assert_eq!(stored_path(&format!("http://localhost:3001{signed}")), "/uploads/emoji_1.png");
        assert_eq!(sign_path("https://example.com/a.png", u, s), "https://example.com/a.png");
        assert_eq!(stored_path("https://example.com/a.png"), "https://example.com/a.png");
    }

    #[test]
    fn signature_is_bound_to_name_user_session_and_expiry() {
        init_secret();
        let (u, s) = (Uuid::new_v4(), Uuid::new_v4());
        let sig = mac("a.png", u, s, 100).finalize().into_bytes();
        assert!(mac("a.png", u, s, 100).verify_slice(&sig).is_ok());
        assert!(mac("b.png", u, s, 100).verify_slice(&sig).is_err());
        assert!(mac("a.png", Uuid::new_v4(), s, 100).verify_slice(&sig).is_err());
        assert!(mac("a.png", u, Uuid::new_v4(), 100).verify_slice(&sig).is_err());
        assert!(mac("a.png", u, s, 101).verify_slice(&sig).is_err());
    }

    #[test]
    fn signs_nested_json() {
        init_secret();
        let mut v = serde_json::json!({ "payload": { "attachment_url": "/uploads/a.png", "content": "/uploads/a.png" } });
        sign_json(&mut v, Uuid::new_v4(), Uuid::new_v4());
        assert!(v["payload"]["attachment_url"].as_str().unwrap().starts_with("/api/v1/files/a.png?"));
        assert_eq!(v["payload"]["content"], "/uploads/a.png"); // only file fields
    }
}
